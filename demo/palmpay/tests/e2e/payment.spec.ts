import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { randomUUID } from 'node:crypto'

test('a café purchase settles once across independent wallet and register sessions', async ({ browser }) => {
  const mobile = await browser.newContext({ viewport: {width:390,height:844}, isMobile:true, hasTouch:true })
  const counter = await browser.newContext({ viewport: {width:1440,height:900} })
  const wallet = await mobile.newPage(), merchant = await counter.newPage()
  const email = randomUUID()+'@example.test'
  mkdirSync('docs/screenshots',{recursive:true})
  await merchant.goto('/merchant')
  await merchant.getByLabel('Operator access key').fill('playwright-operator')
  await merchant.getByRole('button',{name:'Open register'}).click()
  await expect(merchant.getByRole('heading',{name:'Menu'})).toBeVisible()
  await expect(merchant.getByRole('button',{name:/Iced Latte/})).toBeVisible()
  await expect.poll(() => merchant.locator('.product-photo img').evaluateAll(images => images.filter(image => (image as HTMLImageElement).naturalWidth > 0).length)).toBe(7)
  await merchant.getByRole('button',{name:/Iced Latte/}).click()
  await expect(merchant.locator('.cart-foot')).toContainText('25.00')
  await merchant.screenshot({path:'docs/screenshots/merchant-desktop.png'})
  await merchant.setViewportSize({width:1024,height:768})
  await expect(merchant.getByRole('heading',{name:'Current order'})).toBeVisible()
  expect(await merchant.evaluate(()=>document.documentElement.scrollWidth)).toBe(1024)
  await merchant.screenshot({path:'docs/screenshots/merchant-tablet.png'})
  await merchant.setViewportSize({width:1440,height:900})
  await merchant.getByRole('button',{name:'Clear order'}).click()
  await merchant.getByRole('button',{name:'Open wallet'}).click()
  const qr = merchant.getByRole('img',{name:'QR code for Palm Wallet'})
  await expect.poll(()=>qr.evaluate(element=>(element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await merchant.getByRole('button',{name:'Close',exact:true}).click()

  await merchant.getByRole('link',{name:'Enroll customer',exact:true}).click()
  await merchant.getByRole('button',{name:'Create customer wallet',exact:true}).click()
  await merchant.getByLabel('Customer name',{exact:true}).fill('Lena Chan')
  await merchant.getByLabel('Customer email',{exact:true}).fill(email)
  await merchant.getByLabel('Customer password',{exact:true}).fill('testing-password')
  await merchant.getByRole('checkbox').check()
  await merchant.getByRole('button',{name:'Create wallet and enroll'}).click()
  await merchant.getByRole('button',{name:'Simulate enrollment'}).click()
  await expect(merchant.getByRole('heading',{name:'Palm registered'})).toBeVisible()
  await wallet.goto('/wallet')
  const manifest = await mobile.request.get('/manifest.webmanifest')
  expect((await manifest.json()).start_url).toBe('/wallet')
  await expect.poll(()=>wallet.evaluate(async()=>(await navigator.serviceWorker.getRegistration())?.active?.state)).toBe('activated')
  await wallet.getByLabel('Email',{exact:true}).fill(email)
  await wallet.getByLabel('Password',{exact:true}).fill('testing-password')
  await wallet.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(wallet.getByRole('link',{name:'Palm',exact:true})).toHaveCount(0)
  await expect(wallet.locator('.balance')).toContainText('500.00')
  expect(await wallet.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
  await wallet.screenshot({path:'docs/screenshots/wallet-mobile.png'})

  await merchant.getByRole('link',{name:'Checkout'}).click()
  await merchant.getByRole('button',{name:/Iced Latte/}).click()
  await merchant.getByRole('button',{name:'Pay with palm'}).click()
  await expect(merchant.getByRole('heading',{name:'Waiting for palm'})).toBeVisible()
  const id = await merchant.evaluate(()=>localStorage.getItem('palm.activeIntent'))
  await merchant.reload()
  await expect(merchant.getByRole('heading',{name:'Waiting for palm'})).toBeVisible()
  await merchant.getByLabel('Enrolled wallet email').fill(email)
  await merchant.getByRole('button',{name:'Simulate approval'}).click()
  await expect(merchant.getByText('Payment successful')).toBeVisible()
  await expect(wallet.locator('.balance')).toContainText('475.00')
  await expect(wallet.getByRole('status')).toContainText('Payment received')
  await expect(wallet.locator('.wallet-toast')).toHaveCSS('opacity','1')
  await wallet.screenshot({path:'docs/screenshots/wallet-payment.png'})
  await merchant.screenshot({path:'docs/screenshots/merchant-receipt.png'})
  const reference = (await merchant.locator('.receipt-reference').innerText()).trim()
  await wallet.getByRole('status').click()
  await expect(wallet.locator('.receipt-reference')).toHaveText(reference)
  await merchant.reload()
  await wallet.reload()
  await expect(merchant.locator('.receipt-reference')).toHaveText(reference)
  await expect(wallet.locator('.receipt-reference')).toHaveText(reference)

  await mobile.setOffline(true)
  await merchant.getByRole('button',{name:'New order'}).click()
  await merchant.getByRole('button',{name:/Americano/}).click()
  await merchant.getByRole('button',{name:'Pay with palm'}).click()
  await merchant.getByLabel('Enrolled wallet email').fill(email)
  await merchant.getByRole('button',{name:'Simulate approval'}).click()
  await expect(merchant.getByText('Payment successful')).toBeVisible()
  await mobile.setOffline(false)
  await wallet.getByRole('link',{name:'Home',exact:true}).click()
  await expect(wallet.locator('.balance')).toContainText('455.00')
  const duplicate = await counter.request.post('/api/dev/payments/'+id+'/simulate',{data:{email}})
  expect((await duplicate.json()).reference).toBe(reference.trim())
  await expect(wallet.locator('.balance')).toContainText('455.00')
  await wallet.getByRole('button',{name:'Add demo funds',exact:true}).click()
  await wallet.getByRole('button',{name:'Add MOP 100.00',exact:true}).click()
  await expect(wallet.locator('.balance')).toContainText('555.00')
  await mobile.close()
  await counter.close()
})

